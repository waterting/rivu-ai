"use client";

import { useCallback, useEffect, useState } from "react";
import { Download, FileJson, RefreshCw } from "lucide-react";
import styles from "../../dashboard.module.css";
import { authFetch } from "../../../../lib/api";

const authHeaders = () => ({
  Authorization:
    "Bearer " + (typeof window !== "undefined" ? localStorage.getItem("rivu_access_token") || "" : ""),
});

type Dataset = { id: string; name: string; project_id: string; status: string; current_version: number };
type Version = {
  id: string;
  version_number: number;
  version_label: string;
  file_format: string;
  file_size_bytes: number | null;
  row_count: number | null;
  column_count: number | null;
  quality_score: number | null;
  quality_delta: number | null;
  created_at: string;
};

const FORMATS = ["csv", "xlsx", "json", "parquet"] as const;

export default function FormatStudioPage() {
  const [datasets, setDatasets] = useState<Dataset[]>([]);
  const [selected, setSelected] = useState("");
  const [versions, setVersions] = useState<Version[]>([]);
  const [err, setErr] = useState("");
  const [msg, setMsg] = useState("");
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setErr("");
    try {
      const res = await authFetch("/projects/", { headers: authHeaders() });
      const body = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(body.detail?.message || body.detail || "Could not load projects");
      const projects: Array<{ id: string }> = Array.isArray(body.projects) ? body.projects : [];
      const all: Dataset[] = [];
      for (const p of projects) {
        const pr = await authFetch(`/projects/${p.id}`, { headers: authHeaders() });
        if (!pr.ok) continue;
        const pj = await pr.json().catch(() => ({}));
        const list: Dataset[] = Array.isArray(pj.datasets) ? pj.datasets : [];
        all.push(...list);
      }
      setDatasets(all);
      if (all[0]) setSelected(all[0].id);
    } catch (e) {
      setErr(e instanceof Error ? e.message : "Failed to load datasets");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      if (!cancelled) await load();
    })();
    return () => {
      cancelled = true;
    };
  }, [load]);

  const loadVersions = useCallback(async (id: string) => {
    if (!id) return;
    setErr("");
    setMsg("");
    try {
      const r = await authFetch(`/datasets/${id}/versions`, { headers: authHeaders() });
      const j = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(j.detail?.message || j.detail || "Could not load versions");
      setVersions(Array.isArray(j.versions) ? j.versions : []);
    } catch (e) {
      setErr(e instanceof Error ? e.message : "Failed to load versions");
      setVersions([]);
    }
  }, []);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      if (!cancelled) await loadVersions(selected);
    })();
    return () => {
      cancelled = true;
    };
  }, [selected, loadVersions]);

  async function download(datasetId: string, versionNumber: number, format: string) {
    setErr("");
    setMsg("");
    const key = `${datasetId}:${versionNumber}:${format}`;
    setBusy(key);
    try {
      const r = await authFetch(`/datasets/${datasetId}/export/${versionNumber}?format=${format}`, {
        headers: authHeaders(),
      });
      const j = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(j.detail?.message || j.detail || "Export unavailable");
      if (!j.download_url) throw new Error("Export URL missing");
      window.open(j.download_url, "_blank", "noopener,noreferrer");
      setMsg(`Generated ${format.toUpperCase()} download for version ${versionNumber}.`);
    } catch (e) {
      setErr(e instanceof Error ? e.message : "Export failed");
    } finally {
      setBusy(null);
    }
  }

  const fmtSize = (n: number | null) => (n == null ? "—" : n > 1024 * 1024 ? `${(n / 1024 / 1024).toFixed(1)} MB` : `${Math.max(1, Math.round(n / 1024))} KB`);

  return (
    <div>
      <header className={styles.topbar}>
        <div>
          <div className={styles.eyebrow}>RIVU / TOOLS / FORMAT STUDIO</div>
          <h1>Format Studio</h1>
          <p>
            Export any dataset version as CSV, XLSX, JSON or Parquet. Downloads are generated by the export
            endpoint from the stored artifact for that version.
          </p>
        </div>
        <div className={styles.headerActions}>
          <button className={styles.iconBtn} onClick={load}>
            <RefreshCw size={15} /> Refresh
          </button>
        </div>
      </header>

      {err && <div className={styles.error}>{err}</div>}
      {msg && <div className={styles.message}>{msg}</div>}

      <section className={styles.sectionBlock}>
        <h2>Dataset</h2>
        {loading ? (
          <p className={styles.muted}>Loading datasets...</p>
        ) : datasets.length === 0 ? (
          <p className={styles.muted}>No datasets yet. Upload one in Overview.</p>
        ) : (
          <div className={styles.formGrid} style={{ gridTemplateColumns: "1fr" }}>
            <div>
              <label>Dataset</label>
              <select value={selected} onChange={(e) => setSelected(e.target.value)}>
                {datasets.map((d) => (
                  <option key={d.id} value={d.id}>
                    {d.name}
                  </option>
                ))}
              </select>
            </div>
          </div>
        )}
      </section>

      <section className={styles.sectionBlock}>
        <h2>Versions ({versions.length})</h2>
        {versions.length === 0 ? (
          <p className={styles.muted} style={{ marginTop: 10 }}>
            No versions found for this dataset.
          </p>
        ) : (
          <div style={{ display: "grid", gap: 12, marginTop: 12 }}>
            {versions.map((v) => (
              <div key={v.id} className={styles.card}>
                <div className={styles.sectionTitle}>
                  <div>
                    <span>V{v.version_number}</span>
                    <b>{v.version_label || "version"}</b>
                  </div>
                  <div className={styles.statusLive}>{(v.file_format || "—").toUpperCase()}</div>
                </div>
                <p className={styles.muted}>
                  {v.row_count != null ? `${v.row_count.toLocaleString()} rows` : "rows —"} ·{" "}
                  {v.column_count != null ? `${v.column_count} columns` : "columns —"} ·{" "}
                  {fmtSize(v.file_size_bytes)}
                  {v.quality_score != null ? ` · quality ${v.quality_score.toFixed(1)}` : ""}
                  {v.quality_delta ? ` (${v.quality_delta > 0 ? "+" : ""}${v.quality_delta.toFixed(1)} delta)` : ""}
                </p>
                <div style={{ display: "flex", gap: 8, marginTop: 10, flexWrap: "wrap" }}>
                  {FORMATS.map((f) => (
                    <button
                      key={f}
                      className={styles.iconBtn}
                      disabled={busy === `${selected}:${v.version_number}:${f}`}
                      onClick={() => download(selected, v.version_number, f)}
                    >
                      {f === "json" ? <FileJson size={14} /> : <Download size={14} />} {f.toUpperCase()}
                    </button>
                  ))}
                </div>
              </div>
            ))}
          </div>
        )}
      </section>

      <section className={styles.sectionBlock}>
        <h2>Format notes</h2>
        <p>
          A refined version can export to any of the four formats. A raw uploaded version can only export in
          its original format; the export endpoint reports that explicitly instead of producing an empty file.
        </p>
      </section>
    </div>
  );
}